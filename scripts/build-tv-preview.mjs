import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const publicDir = resolve(root, 'public');
const htmlPath = resolve(publicDir, 'tv-preview.html');
const scriptFiles = [
  'tv-preview-weather.js',
  'tv-preview-prayer.js',
  'tv-preview-speed.js',
  'tv-preview.js',
];
let html = await readFile(htmlPath, 'utf8');
const css = await readFile(resolve(publicDir, 'tv-preview.css'), 'utf8');
const cssTag = '<link rel="stylesheet" href="./tv-preview.css" />';
if (!html.includes(cssTag)) throw new Error(`Missing ${cssTag} in ${htmlPath}`);
html = html.replace(cssTag, `<style>\n${css}\n</style>`);
const inlinedScripts = [];
for (const filename of scriptFiles) {
  const source = await readFile(resolve(publicDir, filename), 'utf8');
  const externalTag = `<script src="./${filename}" defer></script>`;
  if (!html.includes(externalTag)) throw new Error(`Missing ${externalTag} in ${htmlPath}`);
  html = html.replace(externalTag, '');
  inlinedScripts.push(`<script>\n${source}\n</script>`);
}
const standalonePath = resolve(publicDir, 'tv-preview-standalone.html');
html = html.replace('</body>', `${inlinedScripts.join('\n')}\n</body>`);
html = html.replace(/^[\t ]+$/gm, '');
await writeFile(standalonePath, html, 'utf8');

const modulePath = resolve(root, 'lib/tvPreviewHtml.ts');
await mkdir(dirname(modulePath), { recursive: true });
const embedded = `// Generated by scripts/build-tv-preview.mjs; do not edit by hand.\nexport const tvPreviewHtml = ${JSON.stringify(html)};\n`;
await writeFile(modulePath, embedded, 'utf8');
console.log(`Built ${standalonePath} (${Buffer.byteLength(html)} bytes)`);
console.log(`Embedded ${modulePath} (${Buffer.byteLength(embedded)} bytes)`);
